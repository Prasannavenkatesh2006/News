class TranslationBundle(BaseModel):
    language: str
    translations: Dict[str, str]


class LanguageInfo(BaseModel):
    code: str
    name: str
    native: str


# ========== API Routes ==========

@router.get("/languages", response_model=list)
def list_languages():
    """List all supported languages."""
    return SUPPORTED_LANGUAGES


@router.get("/translations/{lang}", response_model=TranslationBundle)
def get_translations(lang: str):
    """Get all UI translations for a language."""
    if lang not in TRANSLATIONS:
        # Fall back to English
        lang = "en"
    return TranslationBundle(language=lang, translations=TRANSLATIONS[lang])


@router.get("/translate")
def translate_key(key: str = Query(...), lang: str = Query(default="en")):
    """Translate a single key."""
    translations = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    value = translations.get(key, TRANSLATIONS["en"].get(key, key))
    return {"key": key, "language": lang, "value": value}
